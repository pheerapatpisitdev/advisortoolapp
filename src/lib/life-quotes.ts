/** FNV-1a: small, and the same on every machine, which is all this needs of a hash. */
function hash(text: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h;
}

/** The closing line for one arrangement: the same one every time it is asked for. */
export function quoteFor(seed: string): string {
  return LIFE_QUOTES[hash(seed) % LIFE_QUOTES.length];
}
